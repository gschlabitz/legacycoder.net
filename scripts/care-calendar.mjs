// Materialize the potted-plant care schedule into src/data/care-calendar.yaml
// — the fixed data structure the plants index renders. Dates are derived
// deterministically from each plant page's `plant.care` frontmatter (schema
// in src/content.config.ts): every task gets a calendar from its interval,
// staggered per plant and task by a hash of the slug so the pots don't all
// fall on the same day. Determinism means regenerating after adding a plant
// leaves every existing date untouched. Liquid feeding waters too, so a
// fertilizing day omits that plant from watering.
//
// Usage:
//   npm run care-calendar                              # 12 months from the 1st of this month
//   npm run care-calendar -- --start 2027-01
//   npm run care-calendar -- --start 2027-01 --months 18
//
// Only pages with `plant.schedule: true` are included. English pages are the
// fact source; slugs are locale-independent.

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { parse, stringify } from 'yaml';

const PLANTS_DIR = 'src/content/docs/plants';
const OUTPUT = 'src/data/care-calendar.yaml';
const ORDER = ['watering', 'fertilizing', 'trimming', 'repotting'];
const DAY_MS = 86_400_000;

// Small deterministic hash — the per-plant stagger offset.
export function hash(text) {
  let h = 0;
  for (let i = 0; i < text.length; i += 1) h = (h * 31 + text.charCodeAt(i)) >>> 0;
  return h;
}

// All date math is UTC: calendar dates are plain strings, never instants.
function dayNumber(date) {
  return Math.round(date.getTime() / DAY_MS);
}

export function isDue(task, date, salt) {
  const month = date.getUTCMonth() + 1;
  if (task.months && !task.months.includes(month)) return false;
  const offset = hash(salt);
  if (task.unit === 'days' || task.unit === 'weeks') {
    const interval = task.every * (task.unit === 'weeks' ? 7 : 1);
    return (dayNumber(date) + offset) % interval === 0;
  }
  // Month- and year-sized intervals resolve to a single due day per cycle.
  if (date.getUTCDate() !== 1 + (offset % 28)) return false;
  if (task.unit === 'months') {
    const monthIndex = date.getUTCFullYear() * 12 + date.getUTCMonth();
    return (monthIndex + offset) % task.every === 0;
  }
  // Years: due in the first month of the window (January if year-round).
  const dueMonth = task.months ? Math.min(...task.months) : 1;
  return month === dueMonth && (date.getUTCFullYear() + offset) % task.every === 0;
}

// The materialized schedule: one entry per day that has work, listing plant
// slugs per task. `start` is a { year, month } (month 1–12).
export function generateCalendar({ plants, start, months }) {
  const sorted = [...plants].sort((a, b) => a.slug.localeCompare(b.slug));
  const end = Date.UTC(start.year, start.month - 1 + months, 1);
  const days = [];
  for (
    let date = new Date(Date.UTC(start.year, start.month - 1, 1));
    date.getTime() < end;
    date = new Date(date.getTime() + DAY_MS)
  ) {
    const day = {};
    for (const plant of sorted) {
      let due = ORDER.filter(
        (task) => plant.care[task] && isDue(plant.care[task], date, `${plant.slug}:${task}`),
      );
      // Liquid fertilizer waters as it feeds.
      if (due.includes('fertilizing')) due = due.filter((task) => task !== 'watering');
      for (const task of due) (day[task] ??= []).push(plant.slug);
    }
    if (Object.keys(day).length) days.push({ id: date.toISOString().slice(0, 10), ...day });
  }
  return days;
}

// Scheduled plants from the English pages (the fact source): slug + care.
export function readPlants(dir = PLANTS_DIR) {
  const plants = [];
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.mdx'))) {
    const frontmatter = parse(fs.readFileSync(path.join(dir, file), 'utf8').split(/^---$/m)[1]);
    if (!frontmatter?.plant?.schedule) continue;
    plants.push({ slug: file.replace(/\.mdx$/, ''), care: frontmatter.plant.care });
  }
  return plants;
}

export function parseArgs(args) {
  const options = { months: 12 };
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === '--start') {
      const match = /^(\d{4})-(\d{2})$/.exec(args[++index] ?? '');
      if (!match) throw new Error('--start expects YYYY-MM');
      options.start = { year: Number(match[1]), month: Number(match[2]) };
    } else if (arg === '--months') {
      options.months = Number(args[++index]);
      if (!Number.isInteger(options.months) || options.months < 1)
        throw new Error('--months expects a positive integer');
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }
  return options;
}

const HEADER = `# Generated by \`npm run care-calendar\` — the materialized care schedule
# rendered by the plants index. Derived deterministically from each plant
# page's \`plant.care\` frontmatter, so regenerating after adding a plant (or
# extending the span) leaves existing dates untouched. Liquid feeding waters
# too, so a fertilizing day omits that plant from watering. Values are plant
# slugs; the page localizes titles at render time.
`;

function runCli() {
  const options = parseArgs(process.argv.slice(2));
  const now = new Date();
  const start = options.start ?? { year: now.getFullYear(), month: now.getMonth() + 1 };
  const plants = readPlants();
  const days = generateCalendar({ plants, start, months: options.months });
  // Quote the strings: the site loads this file with js-yaml, which would
  // otherwise parse a bare 2026-08-01 as a Date and mangle the entry ids.
  fs.writeFileSync(
    OUTPUT,
    HEADER + '\n' + stringify(days, { lineWidth: 0, defaultStringType: 'QUOTE_SINGLE', defaultKeyType: 'PLAIN' }),
  );
  const first = days[0]?.id ?? '—';
  const last = days[days.length - 1]?.id ?? '—';
  console.error(
    `Wrote ${OUTPUT}: ${plants.length} plants, ${days.length} care days, ${first} to ${last}.`,
  );
  return 0;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  try {
    process.exitCode = runCli();
  } catch (error) {
    console.error(`care-calendar: ${error.message}`);
    process.exitCode = 1;
  }
}
